"""
ZPA Session Status Codes — authoritative reference data.

Normalized from the Zscaler documentation "Understanding Private Access
Session Status Codes".

Three categories per the documentation's top-level organization:
  * ``error``         — real failures, action required
  * ``info``          — normal closures, "No action required" documented
  * ``policy_block``  — intentional service decisions, working as designed

Component prefixes per the documentation:
  AC      App Connector
  CA      Central Authority
  CLT     Zscaler Client Connector
  SE      Public/Private Service Edge
  ZPA BA  Browser Access service

Severity-hint mapping (our derivation, not in the documentation directly):
  category=error        -> critical by default
  category=policy_block -> warning (some critical when blocking access)
  category=info         -> info (always)

To update when Zscaler publishes a new revision: edit rows here.
This is the single source of truth.

Source URL: https://help.zscaler.com/zpa/understanding-zpa-session-status-codes
"""


# Combined exports
# =====================================================================

ERRORS: List[ZccError] = (
    _CLOUD_AUTH + _CLOUD + _ADMIN_CONSOLE + _REPORT_ISSUE
)

ERRORS_BY_CODE: Dict[str, ZccError] = {
    row["code"]: row for row in ERRORS
}


def get_zcc_error(code: str) -> "ZccError | None":
    """Look up a ZCC error row by code string (e.g. ``"-8"``, ``"3049"``,
    ``"10101"``). Returns None if unknown."""
    if not code:
        return None
    return ERRORS_BY_CODE.get(str(code))


def errors_by_series(series: str) -> List[ZccError]:
    """Return all errors in the given series ("cloud_auth", "cloud",
    "admin_console", or "report_issue")."""
    return [row for row in ERRORS if row.get("series") == series]

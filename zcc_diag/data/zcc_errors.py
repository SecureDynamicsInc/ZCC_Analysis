"""
ZCC numeric error codes — authoritative reference data.

Normalized from the external Zscaler Help reference "Zscaler Client Connector
Errors." Four documented code series:

  * Cloud Authentication Error Codes (-1 to -14) — emitted while ZCC is
    in use and the cloud authentication path fails.
  * Cloud Error Codes (1..28, 1000..1019, 10060..10112) — server-side
    errors the client reports.
  * Admin Console Error Codes (3005..3102) — config / device errors
    surfaced via the admin console flow.
  * Report-an-Issue Error Codes (8790..8810) — UI flow errors when
    submitting an issue from within ZCC.

Each row carries:
  code              — string code (preserves sign for negative codes)
  series            — one of "cloud_auth" | "cloud" | "admin_console"
                                          | "report_issue"
  error_message     — documented from documentation's "Error Message" column
  error_description — documented from documentation's "Error Description" column
  resolution        — documented from documentation's "Resolution" column
  severity_hint     — our derived severity for the chip
                      (most are "critical" since they block ZCC ops)

Source URL: help.zscaler.com/zscaler-client-connector/zscaler-client-connector-errors
"""

from __future__ import annotations

from typing import Dict, List

try:
    from typing import TypedDict
except ImportError:  # pragma: no cover
    TypedDict = dict  # type: ignore


class ZccError(TypedDict, total=False):
    code: str
    series: str
    error_message: str
    error_description: str
    resolution: str
    severity_hint: str


